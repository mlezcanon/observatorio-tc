create table if not exists public.researchers (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null
);

-- Máximo dos investigadores: protege contra habilitaciones accidentales.
create or replace function public.limit_two_researchers()
returns trigger language plpgsql security definer
set search_path = '' as $$
begin
  if (select count(*) from public.researchers) >= 2 then
    raise exception 'Observatorio DIC: solo se permiten dos investigadores autorizados';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_limit_two_researchers on public.researchers;
create trigger trg_limit_two_researchers before insert on public.researchers
for each row execute function public.limit_two_researchers();
revoke all on function public.limit_two_researchers() from public, anon, authenticated;

create table if not exists public.cases (
  id bigint generated by default as identity primary key,
  expediente text not null unique,
  title text not null,
  publication_year integer check (publication_year between 1990 and 2200),
  matter text not null default 'Por clasificar',
  relevance text not null default 'Pendiente' check (relevance in ('Pendiente','Directa','Indirecta','No relacionada')),
  review_status text not null default 'Pendiente' check (review_status in ('Pendiente','Validado','Excluido')),
  summary text not null default '',
  source_url text,
  provenance text not null default 'Carga manual sin validar',
  published boolean not null default false,
  created_by uuid references auth.users(id),
  modified_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  modified_at timestamptz not null default now(),
  constraint valid_publication check (
    published = false or (
      review_status = 'Validado'
      and relevance in ('Directa','Indirecta')
      and length(trim(summary)) >= 25
      and source_url like 'https://www.tc.gob.pe/jurisprudencia/%'
    )
  )
);

create table if not exists public.case_notes (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  author_id uuid not null references auth.users(id),
  note text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.case_sources (
  case_id bigint primary key references public.cases(id) on delete cascade,
  excerpt text not null,
  full_character_count integer not null,
  is_excerpt boolean not null,
  sha256 text not null,
  fetched_at timestamptz not null default now()
);

create table if not exists public.case_history (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  editor_id uuid references auth.users(id),
  action text not null,
  recorded_at timestamptz not null default now(),
  snapshot jsonb not null
);

create or replace function public.track_case_change()
returns trigger language plpgsql security definer
set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    new.created_by := (select auth.uid());
  else
    new.created_by := old.created_by;
  end if;
  new.modified_by := (select auth.uid());
  new.modified_at := now();
  return new;
end;
$$;

create or replace function public.log_case_change()
returns trigger language plpgsql security definer
set search_path = '' as $$
begin
  insert into public.case_history (case_id, editor_id, action, snapshot)
  values (new.id, (select auth.uid()), tg_op, to_jsonb(new));
  return new;
end;
$$;

drop trigger if exists trg_case_change on public.cases;
create trigger trg_case_change before insert or update on public.cases
for each row execute function public.track_case_change();

drop trigger if exists trg_case_history on public.cases;
create trigger trg_case_history after insert or update on public.cases
for each row execute function public.log_case_change();

revoke all on function public.track_case_change() from public, anon, authenticated;
revoke all on function public.log_case_change() from public, anon, authenticated;

alter table public.researchers enable row level security;
alter table public.cases enable row level security;
alter table public.case_notes enable row level security;
alter table public.case_sources enable row level security;
alter table public.case_history enable row level security;

-- Tabla de miembros: solo leen su propia pertenencia. No pueden crear usuarios autorizados.
drop policy if exists researchers_self_read on public.researchers;
create policy researchers_self_read on public.researchers
for select to authenticated using (user_id = (select auth.uid()));

-- Público: solo registros aprobados. Investigadores: pueden ver todos.
drop policy if exists cases_public_read on public.cases;
create policy cases_public_read on public.cases
for select to anon, authenticated using (published is true);

drop policy if exists cases_research_read on public.cases;
create policy cases_research_read on public.cases
for select to authenticated using (
  exists (select 1 from public.researchers r where r.user_id = (select auth.uid()))
);

drop policy if exists cases_research_insert on public.cases;
create policy cases_research_insert on public.cases
for insert to authenticated with check (
  exists (select 1 from public.researchers r where r.user_id = (select auth.uid()))
);

drop policy if exists cases_research_update on public.cases;
create policy cases_research_update on public.cases
for update to authenticated
using (exists (select 1 from public.researchers r where r.user_id = (select auth.uid())))
with check (exists (select 1 from public.researchers r where r.user_id = (select auth.uid())));

-- Sin DELETE sobre expedientes: despublicar o corregir para conservar trazabilidad.
drop policy if exists notes_research_read on public.case_notes;
create policy notes_research_read on public.case_notes
for select to authenticated using (
  exists (select 1 from public.researchers r where r.user_id = (select auth.uid()))
);

drop policy if exists notes_author_insert on public.case_notes;
create policy notes_author_insert on public.case_notes
for insert to authenticated with check (
  author_id = (select auth.uid())
  and exists (select 1 from public.researchers r where r.user_id = (select auth.uid()))
);

